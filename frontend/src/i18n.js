// Fallback helper function to ensure every language resolves smoothly
export function getI18n(lang = 'en') {
  const selected = TRANSLATIONS[lang] || TRANSLATIONS['hi'] || TRANSLATIONS['en'];
  const extra = DOMAIN_EXTRAS[lang] || DOMAIN_EXTRAS['hi'] || DOMAIN_EXTRAS['en'] || {};
  const enExtra = DOMAIN_EXTRAS['en'] || {};

  return (key, fallback = '') => {
    if (extra && extra[key] !== undefined) return extra[key];
    if (selected && selected[key] !== undefined) return selected[key];
    if (enExtra && enExtra[key] !== undefined) return enExtra[key];
    if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key] !== undefined) return TRANSLATIONS['en'][key];
    return fallback;
  };
}

